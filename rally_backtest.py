"""Backtest for rally_check.py: are rallies on light volume (and narrow leadership) fragile?

Usage: FMP_API_KEY=... python rally_backtest.py > rally_results.md
Data: FMP daily bars for SPY, RSP, QQQ, QQQE (QQQE starts 2012). One signal per episode
(no repeat within 20 sessions); outcomes need 60 forward sessions, so the newest ~3 months
are not scored.
"""
from __future__ import annotations

import json
import os
import statistics as st
import urllib.request

import rally_check as rc

BASE = "https://financialmodelingprep.com/stable/historical-price-eod/full"


def fetch(sym: str, key: str) -> list[dict]:
    url = f"{BASE}?symbol={sym}&from=2005-01-01&apikey={key}"
    with urllib.request.urlopen(url, timeout=60) as r:
        rows = json.loads(r.read().decode())
    return sorted(rows, key=lambda x: x["date"])


def single_days(bars, thr):
    c = [b["close"] for b in bars]; v = [b["volume"] for b in bars]
    out = []
    for i in range(51, len(bars) - 20):
        r = c[i] / c[i - 1] - 1
        if r < thr:
            continue
        rv = v[i] / st.mean(v[i - 50:i])
        out.append(dict(rv=rv, f10=c[i + 10] / c[i] - 1, f20=c[i + 20] / c[i] - 1,
                        gb=min(c[i + 1:i + 11]) < c[i - 1]))
    return out


def rallies(bars, ew_bars, gain):
    ew = {b["date"]: b["close"] for b in ew_bars}
    c = [b["close"] for b in bars]; v = [b["volume"] for b in bars]; d = [b["date"] for b in bars]
    out, last = [], -99
    for i in range(rc.YEAR + 8, len(bars) - 60):
        if d[i] not in ew or d[i - 20] not in ew:
            continue
        g = c[i] / c[i - 20] - 1
        if g < gain or c[i] < rc.NEAR_HIGH * max(c[i - rc.YEAR + 1:i + 1]) or i - last < 20:
            continue
        last = i
        vr = st.mean(v[i - 19:i + 1]) / st.mean(v[i - 119:i - 19])
        gap = g - (ew[d[i]] / ew[d[i - 20]] - 1)
        mdd = min(c[i + 1:i + 61]) / c[i] - 1
        out.append(dict(d=d[i], thin=vr < rc.LOW_VOLUME, narrow=gap >= rc.NARROW_GAP,
                        f60=c[i + 60] / c[i] - 1, mdd=mdd))
    return out


def row(label, rows):
    if not rows:
        return f"| {label} | 0 | | | |"
    n = len(rows)
    return (f"| {label} | {n} | {100 * st.mean(x['f60'] for x in rows):+.1f}% | "
            f"{100 * st.median(x['mdd'] for x in rows):+.1f}% | "
            f"{100 * sum(x['mdd'] <= -0.07 for x in rows) / n:.0f}% |")


def main():
    key = os.environ["FMP_API_KEY"]
    data = {s: fetch(s, key) for s in ("SPY", "RSP", "QQQ", "QQQE")}
    print("# Rally quality backtest (rally_check.py)\n")
    print(f"FMP daily bars through {data['SPY'][-1]['date']}. Generated by rally_backtest.py.\n")
    print("## 1. Single up days, by volume vs the 50-day average\n")
    print("| Index | Day gain | Volume | n | Fwd 10d | Fwd 20d | Gain erased in 10d |")
    print("|---|---|---|---|---|---|---|")
    for s in ("SPY", "QQQ"):
        for thr in (0.01, 0.015):
            rows = single_days(data[s], thr)
            for lab, f in (("light <0.8x", lambda x: x["rv"] < 0.8),
                           ("normal", lambda x: 0.8 <= x["rv"] <= 1.2),
                           ("heavy >1.2x", lambda x: x["rv"] > 1.2)):
                rr = [x for x in rows if f(x)]
                if rr:
                    print(f"| {s} | >= {100 * thr:.1f}% | {lab} | {len(rr)} | "
                          f"{100 * st.mean(x['f10'] for x in rr):+.2f}% | "
                          f"{100 * st.mean(x['f20'] for x in rr):+.2f}% | "
                          f"{100 * sum(x['gb'] for x in rr) / len(rr):.0f}% |")
    print("\n## 2. 20-day rallies into a 52-week high, by volume and breadth\n")
    print("Light volume = 20d avg / prior 100d avg < 0.85. Narrow = beat the equal-weight twin "
          "(RSP / QQQE) by >= 2 pts over the 20 days.\n")
    for s, e in rc.PAIRS.items():
        for gain in (0.03, 0.05):
            rows = rallies(data[s], data[e], gain)
            print(f"\n**{s}, 20-day gain >= {100 * gain:.0f}%**\n")
            print("| Rally type | n | Fwd 60d | Median worst drop (60d) | Fell 7%+ within 60d |")
            print("|---|---|---|---|---|")
            print(row("broad, normal volume", [x for x in rows if not x["thin"] and not x["narrow"]]))
            print(row("broad, light volume", [x for x in rows if x["thin"] and not x["narrow"]]))
            print(row("narrow, normal volume", [x for x in rows if not x["thin"] and x["narrow"]]))
            print(row("**narrow + light volume (FRAGILE)**", [x for x in rows if x["thin"] and x["narrow"]]))
            fr = [x for x in rows if x["thin"] and x["narrow"]]
            if fr:
                print("\nFRAGILE signals (worst drop in the next 60 sessions): "
                      + ", ".join(f"{x['d']} ({100 * x['mdd']:+.0f}%)" for x in fr))


if __name__ == "__main__":
    main()
